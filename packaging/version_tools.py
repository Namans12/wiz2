"""Single-source version helpers for the packaging scripts.

``src/__init__.py`` holds the one real version number (``__version__``).  Everything in
``packaging/`` reads it through this module, without importing the application package.

Command line (used by ``build_windows.ps1``)::

    python packaging/version_tools.py --print                  # prints e.g. 1.0.0
    python packaging/version_tools.py --windows-file PATH      # writes a PyInstaller version file
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INIT_FILE = ROOT / "src" / "__init__.py"
VERSION_RE = re.compile(r"^\d+\.\d+\.\d+$")
_ASSIGNMENT_RE = re.compile(r"""^__version__\s*=\s*["']([^"']+)["']\s*$""", re.MULTILINE)

APP_NAME = "WizLight"
COMPANY = "WizLight"
DESCRIPTION = "WizLight - WiZ smart light controller"
COPYRIGHT = "MIT License"


def read_version(init_file: Path = INIT_FILE) -> str:
    """Return ``__version__`` from ``src/__init__.py`` (parsed as text, never imported)."""
    match = _ASSIGNMENT_RE.search(init_file.read_text(encoding="utf-8"))
    if match is None:
        raise ValueError(f"No __version__ assignment found in {init_file}")
    version = match.group(1)
    if not VERSION_RE.match(version):
        raise ValueError(f"__version__ {version!r} is not MAJOR.MINOR.PATCH")
    return version


def version_tuple(version: str) -> tuple[int, int, int, int]:
    major, minor, patch = (int(part) for part in version.split("."))
    return (major, minor, patch, 0)


def windows_version_info(version: str) -> str:
    """Return the text of a PyInstaller ``VSVersionInfo`` file for ``version``."""
    numeric = version_tuple(version)
    dotted = ".".join(str(part) for part in numeric)
    strings = [
        ("CompanyName", COMPANY),
        ("FileDescription", DESCRIPTION),
        ("FileVersion", dotted),
        ("InternalName", APP_NAME),
        ("LegalCopyright", COPYRIGHT),
        ("OriginalFilename", f"{APP_NAME}.exe"),
        ("ProductName", APP_NAME),
        ("ProductVersion", version),
    ]
    string_lines = ",\n".join(f"        StringStruct({key!r}, {value!r})" for key, value in strings)
    return f"""# UTF-8
# Generated by packaging/version_tools.py from src/__init__.py - do not edit.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={numeric!r},
    prodvers={numeric!r},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable(
        '040904B0',
        [
{string_lines}
        ])
    ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


def write_windows_version_file(path: Path, version: str | None = None) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(windows_version_info(version or read_version()), encoding="utf-8")
    return path


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--print", action="store_true", dest="print_version", help="print the version")
    parser.add_argument("--windows-file", type=Path, help="write a PyInstaller version resource file")
    args = parser.parse_args()
    if args.windows_file:
        write_windows_version_file(args.windows_file)
        print(f"Wrote {args.windows_file}")
    if args.print_version or not args.windows_file:
        print(read_version())


if __name__ == "__main__":
    main()
